// A compact, LLM-facing description of the catalog: component tags grouped by
// family, with prop hints for the curated ones.
export function describeCatalog(): string {
  const lines: string[] = [];
  for (const [family, names] of Object.entries(catalogFamilies)) {
    const rendered = names.map((name) => {
      const props = catalogSchemas[name]?.props;
      if (!props) return name;
      const hints = Object.entries(props)
        .map(([prop, s]) => (s.options ? `${prop}: ${s.options.join("|")}` : prop))
        .join(", ");
      return `${name} (${hints})`;
    });
    lines.push(`- ${family}: ${rendered.join(", ")}`);
  }
  return lines.join("\n");
}
